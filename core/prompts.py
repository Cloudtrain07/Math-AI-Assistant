def build_system_prompt(
    level: str,
    mode: str,
    answer_style: str | None = None,
    stage: str | None = None,
) -> str:
    """按学段、模式与阶段组装系统提示词。"""
    level_hint = LEVEL_HINTS.get(level, LEVEL_HINTS["高中"])
    prompt = (
        BASE_RULES
        + "\n\n"
        + FORMAT_RULES
        + "\n\n"
        + MATH_RIGOR_RULES
        + "\n\n"
        + TYPE_TEMPLATES
        + "\n\n【当前设置】\n"
        + f"- 用户学段：{level}（{level_hint}）\n"
        + f"- 教学模式：{mode}"
    )
    if mode == MODE_INTERACTIVE:
        prompt += "\n\n" + INTERACTIVE_MODE_RULES
        if stage and stage in STAGE_HINTS:
            prompt += "\n\n" + STAGE_HINTS[stage]
    elif mode == MODE_ANSWER:
        prompt += "\n\n" + ANSWER_MODE_RULES
        if answer_style:
            style_hint = ANSWER_STYLE_HINTS.get(
                answer_style, ANSWER_STYLE_HINTS["完整步骤+答案"]
            )
            prompt += f"\n- 解答风格：{answer_style}（{style_hint}）"
    return prompt
